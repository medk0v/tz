export function projectAppearanceText(locale: Locale) {
  const messages = locale === "ru" ? ru : locale === "ro" ? ro : en;
  return (key: ProjectAppearanceTextKey, values: Record<string, string> = {}): string =>
    messages[key].replace(/\{(\w+)\}/g, (match, name: string) => values[name] ?? match);
}
