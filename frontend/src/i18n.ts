const catalogs: Record<Locale, Partial<Catalog>> = { en, ru, ro };
const localeCodes: Record<Locale, string> = { en: "en-US", ru: "ru-RU", ro: "ro-RO" };

export const LOCALE_STORAGE_KEY = `${productNamespace}-admin-locale`;

export type Translate = (
  key: MessageKey,
  params?: Record<string, string | number>,
) => string;

export interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translate;
  formatDate: (value: string | Date, options: Intl.DateTimeFormatOptions) => string;
}

export const I18nContext = createContext<I18nValue | null>(null);

/// The workspace speaks the language the served document declares; Russian is
/// the shipped default.
export function initialLocale(): Locale {
  const declared = document.documentElement.lang;
  return declared === "en" || declared === "ro" ? declared : "ru";
}

/** `hourCycle` forces 12- or 24-hour times; without it they follow the interface language. */
export function createI18n(locale: Locale, setLocale: (locale: Locale) => void, hourCycle?: HourCycle): I18nValue {
  const t: Translate = (key, params) => {
    const template = catalogs[locale][key] ?? catalogs.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (
      params?.[name] === undefined ? match : String(params[name])
    ));
  };
  return {
    locale,
    setLocale,
    t,
    formatDate: (value, options) => new Intl.DateTimeFormat(localeCodes[locale], withHourCycle(options, hourCycle)).format(new Date(value)),
  };
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("I18nContext is missing.");
  return value;
}

export function localizedError(cause: unknown, t: Translate, fallback: MessageKey): string {
  const message = cause instanceof Error ? cause.message.toLowerCase() : "";
  if (message.includes("demo_readonly")) return t("demo.readonlyAction");
  if (message.includes("invalid email or password") || message.includes("invalid_credentials")) {
    return t("login.invalidCredentials");
  }
  if (message.includes("session or access token is invalid") || message.includes("unauthorized")) {
    return t("errors.sessionExpired");
  }
  if (message.includes("forbidden")) return t("errors.forbidden");
  return t(fallback);
}

